#!/usr/bin/env node
/**
 * CI guard: regenerate the API client from the committed contract and fail if
 * anything under src/api/ differs from what's committed.
 *
 * Catches: hand-edits to src/api/generated, forgetting `yarn api:gen` after
 * pulling a new spec, and a stale ENDPOINTS.md.
 */
import { execSync } from "node:child_process";

const run = (cmd) => execSync(cmd, { stdio: "inherit" });

run("yarn -s api:gen");

const dirty = execSync("git status --porcelain -- src/api", { encoding: "utf8" })
  .split("\n")
  .filter((line) => line && !/\/\._[^/]*$/.test(line)); // ignore macOS metadata

if (dirty.length) {
  process.stderr.write(
    "\napi:check ✖ src/api is out of sync with openapi/openapi.json:\n" +
      `${dirty.map((l) => `  ${l}`).join("\n")}\n\n` +
      "Run `yarn api:gen` and commit the result. Never edit src/api/generated by hand.\n",
  );
  execSync("git --no-pager diff --stat -- src/api", { stdio: "inherit" });
  process.exit(1);
}
process.stdout.write("api:check ✔ generated client matches the committed contract\n");
