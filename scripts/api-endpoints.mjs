#!/usr/bin/env node
/**
 * Generate src/api/ENDPOINTS.md — a one-line-per-endpoint index of the API
 * contract, mapped to the Orval-generated function that calls it.
 *
 * Read this before building a feature: if an endpoint isn't listed here, it
 * isn't in the contract — add it to the backend spec first, don't hand-write
 * a fetch.
 *
 * Runs automatically as part of `yarn api:gen`.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = resolve(ROOT, "openapi/openapi.json");
const GENERATED = resolve(ROOT, "src/api/generated");
const OUT = resolve(ROOT, "src/api/ENDPOINTS.md");
const METHODS = ["get", "post", "put", "patch", "delete"];

const spec = JSON.parse(readFileSync(SPEC, "utf8"));

// Map every exported async function in the generated client → its folder (tag).
const generatedFns = new Map();
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith("._")) continue; // macOS metadata on external drives
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "models") walk(full);
    } else if (entry.name.endsWith(".ts")) {
      const src = readFileSync(full, "utf8");
      for (const [, name] of src.matchAll(/^export const (\w+) = async/gm)) {
        generatedFns.set(name, full.slice(GENERATED.length + 1));
      }
    }
  }
};
if (existsSync(GENERATED)) walk(GENERATED);

// Orval's default naming when the spec has no operationId:
// method + PascalCase(path segments), braces stripped.
//   DELETE /api/budgets/{id}/income/{incomeId} → deleteApiBudgetsIdIncomeIncomeId
const pascal = (s) =>
  s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const orvalName = (method, path, op) =>
  op.operationId ?? method + path.split("/").filter(Boolean).map(pascal).join("");

const schemaName = (content) => {
  const media = content?.["application/json"] ?? content?.["multipart/form-data"];
  const schema = media?.schema;
  if (!schema) return "";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.type === "array" && schema.items?.$ref) {
    return `${schema.items.$ref.split("/").pop()}[]`;
  }
  return schema.type ?? "";
};

const successResponse = (responses = {}) => {
  const code = Object.keys(responses).find((c) => c.startsWith("2"));
  return code ? `${code} ${schemaName(responses[code].content)}`.trim() : "";
};

const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s+/g, " ")
    .trim();

const byTag = new Map();
let missing = 0;
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const fn = orvalName(method, path, op);
    const found = generatedFns.has(fn);
    if (!found) missing++;
    const tag = op.tags?.[0] ?? "untagged";
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push({
      method: method.toUpperCase(),
      path,
      fn: found ? `\`${fn}\`` : `⚠️ \`${fn}\` not generated`,
      summary: (op.deprecated ? "**DEPRECATED** " : "") + (op.summary ?? ""),
      body: schemaName(op.requestBody?.content),
      res: successResponse(op.responses),
    });
  }
}

const total = [...byTag.values()].reduce((n, rows) => n + rows.length, 0);
const lines = [
  "<!-- GENERATED by scripts/api-endpoints.mjs from openapi/openapi.json — do not edit. -->",
  "",
  "# API endpoints",
  "",
  `${spec.info?.title ?? "API"} — OpenAPI ${spec.info?.version ?? ""} · ${total} operations.`,
  "",
  "Import functions from `@/api/generated/<tag>/<tag>` **only inside**",
  "`src/features/*/api/`. Not listed here = not in the contract: add it to the",
  "backend spec, then `yarn api:sync`.",
  "",
];
for (const tag of [...byTag.keys()].sort()) {
  lines.push(`## ${tag}`, "");
  lines.push("| Method | Path | Function | Summary | Body | Success |");
  lines.push("| --- | --- | --- | --- | --- | --- |");
  for (const r of byTag.get(tag)) {
    lines.push(
      `| ${r.method} | \`${cell(r.path)}\` | ${r.fn} | ${cell(r.summary)} | ${cell(r.body)} | ${cell(r.res)} |`,
    );
  }
  lines.push("");
}

writeFileSync(OUT, lines.join("\n"));
process.stdout.write(
  `api:endpoints ✔ wrote src/api/ENDPOINTS.md (${total} operations` +
    `${missing ? `, ${missing} without a generated function` : ""})\n`,
);
if (missing) process.exitCode = 1;
